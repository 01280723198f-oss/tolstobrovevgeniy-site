/** Ссылки в подвал всех страниц. Пусто, пока оператор не заполнен. */
function footerLinks() {
  if (!ready()) return "";
  return `<nav class="footer-legal"><a href="/privacy/">Политика конфиденциальности</a> · <a href="/consent/">Согласие на обработку данных</a></nav>`;
}

/** Плашка про cookie: один раз, до нажатия «Понятно». Хранится в localStorage. */
function cookieNote() {
  if (!ready()) return "";
  return `
  <div class="cookie-note" id="cookie-note" hidden>
    <p>Сайт использует cookie и сервисы аналитики, чтобы понимать, какие инструкции полезны. Продолжая пользоваться сайтом, вы соглашаетесь с <a href="/privacy/">политикой</a> и <a href="/consent/">обработкой данных</a>.</p>
    <button type="button" id="cookie-ok">Понятно</button>
  </div>
  <script>(function(){try{if(localStorage.getItem("cookie-ok"))return}catch(e){}var n=document.getElementById("cookie-note");
  if(!n)return;n.hidden=false;document.getElementById("cookie-ok").onclick=function(){try{localStorage.setItem("cookie-ok",Date.now())}catch(e){}n.hidden=true}})();</script>`;
}

module.exports = { ready, missing, privacyBody, consentBody, footerLinks, cookieNote };
