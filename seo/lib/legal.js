/* Политика конфиденциальности, согласие на обработку ПДн и плашка про cookie.
   Ничего не публикуется, пока в config.js не заполнен оператор (имя, статус, email):
   недописанная политика с заглушками на живом сайте хуже, чем никакой.
   Текст собирается из того, что сайт реально включает: нет счётчика — нет строки про него. */

const C = require("../config");
const { escapeHtml } = require("./text");

const NEED = ["name", "status", "email"];
const op = () => C.operator || {};

function missing() {
  return NEED.filter(k => !String(op()[k] || "").trim());
}

const ready = () => missing().length === 0;

/** Кто и что получает — по фактически включённым сервисам. */
function processors() {
  const a = C.analytics || {}, list = [];
  if (a.metrikaId) list.push({
    who: "ООО «Яндекс» (Россия), сервис Яндекс Метрика",
    what: "cookie, IP-адрес, сведения о браузере и устройстве, адреса посещённых страниц, источник перехода"
      + (a.metrikaOptions && a.metrikaOptions.webvisor ? ", действия на странице (Вебвизор: прокрутка, клики, движение курсора)" : ""),
    where: "Россия"
  });
  if (a.ga4Id) list.push({
    who: "Google LLC (США), сервис Google Analytics",
    what: "cookie, IP-адрес, сведения о браузере и устройстве, посещённые страницы", where: "США — трансграничная передача"
  });
  if (a.own && a.own.url) list.push({
    who: "собственный счётчик сайта (облачная база Supabase)",
    what: "адрес страницы, источник перехода и UTM-метки, события на странице (дочитал, нажал на кнопку), без имени и контактов",
    where: "облачное хранилище вне России — трансграничная передача"
  });
  list.push({
    who: "GitHub Inc. (США), хостинг GitHub Pages",
    what: "IP-адрес и технические сведения запроса в журналах сервера", where: "США — трансграничная передача"
  });
  return list;
}

function operatorLine() {
  const o = op();
  return `${escapeHtml(o.status)} ${escapeHtml(o.name)}` + (o.inn ? `, ИНН ${escapeHtml(o.inn)}` : "")
    + (o.ogrnip ? `, ОГРНИП ${escapeHtml(o.ogrnip)}` : "");
}

const today = () => op().updated
  || new Date().toLocaleDateString("ru-RU", { day: "numeric", month: "long", year: "numeric" }).replace(/\s*г\.$/, "");

function privacyBody() {
  const o = op(), site = C.origin.replace(/^https?:\/\//, "");
  return `
      <p class="lead">Редакция от ${escapeHtml(today())}. Документ объясняет, какие данные собирает сайт ${site}, зачем и как от этого отказаться.</p>

      <h2>1. Кто оператор</h2>
      <p>Оператор персональных данных — ${operatorLine()} (далее — Оператор). Связь по вопросам данных: <a href="mailto:${escapeHtml(o.email)}">${escapeHtml(o.email)}</a>.</p>
      <p>Политика составлена по Федеральному закону от 27.07.2006 № 152-ФЗ «О персональных данных» и действует для всех страниц сайта ${site}.</p>

      <h2>2. Какие данные собираются</h2>
      <p>На сайте нет форм: имя, телефон и email сайт не спрашивает. Автоматически обрабатываются только технические данные:</p>
      <ul>
        <li>cookie и похожие идентификаторы браузера;</li>
        <li>IP-адрес, тип устройства, браузер, язык, разрешение экрана;</li>
        <li>адреса посещённых страниц, время посещения, источник перехода и UTM-метки;</li>
        <li>действия на странице: прокрутка, нажатия на кнопки и ссылки.</li>
      </ul>
      <p>UTM-метки хранятся в браузере посетителя (localStorage) 30 дней, чтобы понять, из какой публикации пришёл человек.</p>

      <h2>3. Зачем</h2>
      <ul>
        <li>понимать, какие инструкции читают и дочитывают, и улучшать их;</li>
        <li>считать переходы из публикаций и в Telegram-канал;</li>
        <li>обеспечивать работу и безопасность сайта.</li>
      </ul>
      <p>Данные не используются для рекламных рассылок и не продаются.</p>

      <h2>4. Основание</h2>
      <p>Согласие посетителя на обработку персональных данных (<a href="/consent/">текст согласия</a>). Согласие даётся при продолжении пользования сайтом после уведомления о cookie и может быть отозвано.</p>

      <h2>5. Кому передаются</h2>
      <p>Данные обрабатываются с помощью сервисов:</p>
      <ul>
        ${processors().map(p => `<li><b>${escapeHtml(p.who)}</b> — ${escapeHtml(p.what)}. Хранение: ${escapeHtml(p.where)}.</li>`).join("\n        ")}
      </ul>
      <p>Страны, куда передаются данные, перечислены выше. Посетитель, который не согласен на трансграничную передачу, может отключить cookie или не пользоваться сайтом.</p>

      <h2>6. Сроки</h2>
      <p>Данные хранятся до достижения целей, но не дольше 2 лет, либо до отзыва согласия. Сроки хранения у сервисов аналитики определяются их правилами.</p>

      <h2>7. Как отказаться</h2>
      <ul>
        <li>запретить или удалить cookie в настройках браузера;</li>
        <li>установить <a href="https://yandex.ru/support/metrica/general/opt-out.html" rel="noopener" target="_blank">блокировщик Яндекс Метрики</a>;</li>
        <li>написать на <a href="mailto:${escapeHtml(o.email)}">${escapeHtml(o.email)}</a> — отозвать согласие, узнать, какие данные обрабатываются, потребовать их уточнить или удалить. Ответ — в течение 10 рабочих дней.</li>
      </ul>

      <h2>8. Защита</h2>
      <p>Сайт работает по HTTPS. Доступ к статистике есть только у Оператора. Ссылки на Telegram ведут на сторонний сервис со своей политикой.</p>

      <h2>9. Изменения</h2>
      <p>Оператор может обновлять политику. Актуальная редакция всегда по адресу ${C.origin}/privacy/.</p>`;
}

